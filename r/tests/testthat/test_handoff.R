test_that("a fetched stream survives result cleanup, garbage collection and export", {
  result <- native_probe_result(FALSE)
  withr::defer(native_result_clear(result))
  stream <- native_result_fetch(result, -1)
  native_result_clear(result)
  expect_s3_class(stream, "nanoarrow_array_stream")
  gc()
  destination <- nanoarrow::nanoarrow_allocate_array_stream()
  nanoarrow::nanoarrow_pointer_export(stream, destination)
  rm(stream)
  gc()
  expect_true(nanoarrow::nanoarrow_pointer_is_valid(destination))
  frame <- stream_frame(destination)
  expect_identical(frame$s_empty[1], "")
  expect_identical(as.character(frame$big[1]), "9007199254740993")
})
